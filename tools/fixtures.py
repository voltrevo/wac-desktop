#!/usr/bin/env python3
"""Writes test/fixtures.wac: small archives, made by Python's own zipfile and tarfile, as byte arrays."""
import gzip, io, os, tarfile, zipfile

def zbasic():
    b = io.BytesIO()
    with zipfile.ZipFile(b, "w") as z:
        z.writestr(zipfile.ZipInfo("readme.txt", (2024, 3, 2, 14, 5, 0)), "hello zip\n")
        i = zipfile.ZipInfo("src/lib/deep.txt", (2023, 1, 9, 8, 30, 0)); i.compress_type = zipfile.ZIP_DEFLATED
        z.writestr(i, "deflated " * 40)
        z.writestr("src/main.c", "int main(void) { return 0; }\n")
        z.writestr("empty/", "")
        z.writestr("café.txt", "utf8 name")
        z.comment = b"a comment"
    return b.getvalue()

def zcp437():
    # A name with the UTF-8 flag clear and a byte that is not UTF-8: 0x82 is e-acute in code page 437.
    b = io.BytesIO()
    with zipfile.ZipFile(b, "w") as z:
        z.writestr("x", "cp437")
    # Rename "x" to 0x82 in both headers: the same length, and the UTF-8 flag is already clear.
    out = bytearray(b.getvalue())
    for sig, name_off in ((b"PK\x03\x04", 30), (b"PK\x01\x02", 46)):
        at = out.find(sig)
        out[at + name_off] = 0x82
    return bytes(out)

def zprefixed():
    return b"#!/bin/sh\necho self-extracting\nexit 0\n" + zbasic()

def tbasic():
    b = io.BytesIO()
    with tarfile.open(fileobj=b, mode="w", format=tarfile.GNU_FORMAT) as t:
        def add(name, data, mtime=1709388300):
            i = tarfile.TarInfo(name); i.size = len(data); i.mtime = mtime
            t.addfile(i, io.BytesIO(data))
        d = tarfile.TarInfo("pkg"); d.type = tarfile.DIRTYPE; d.mtime = 1709388300; t.addfile(d)
        add("pkg/a.txt", b"alpha\n")
        add("pkg/" + "long" * 30 + ".txt", b"a long name\n")
    return b.getvalue()

def tpax():
    b = io.BytesIO()
    with tarfile.open(fileobj=b, mode="w", format=tarfile.PAX_FORMAT) as t:
        data = b"pax body"
        i = tarfile.TarInfo("dir/" + "p" * 120 + ".bin"); i.size = len(data); i.mtime = 0
        t.addfile(i, io.BytesIO(data))
    return b.getvalue()

def tgz():
    return gzip.compress(tbasic(), mtime=0)

def emit(name, data):
    rows = [", ".join("0x%02X" % c for c in data[i:i + 24]) for i in range(0, len(data), 24)]
    return "export u8[] %s() {\n  return [\n    %s,\n  ];\n}\n" % (name, ",\n    ".join(rows))

here = os.path.dirname(os.path.abspath(__file__))
parts = ["// Generated by tools/fixtures.py — small archives made by Python's zipfile and tarfile.\n"]
for n, f in (("zipBasic", zbasic), ("zipCp437", zcp437), ("zipPrefixed", zprefixed),
             ("tarBasic", tbasic), ("tarPax", tpax), ("tarGz", tgz)):
    parts.append(emit(n, f()))
open(os.path.join(here, "..", "test", "fixtures.wac"), "w").write("\n".join(parts))
