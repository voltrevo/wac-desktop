#!/usr/bin/env python3
"""Writes src/desk/seed.wac: what a new desktop starts with — a welcome note and the demo archive."""
import os

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..")

WELCOME = """# Welcome

This is a desktop that runs in your browser tab: windows, a taskbar, and a disk of its own.
It is written in [wac](https://github.com/voltrevo/wac) and compiled to WebAssembly.

## Try this

1. Double-click **demo.zip** on the desktop. It opens in Files, already inside — nothing is unpacked.
2. Look around: Markdown renders, JSON folds, CSV becomes a table, code is highlighted.
3. Press **Extract here**. The archive becomes a folder next to it.
4. Open a text file from that folder and change it in the **Editor**. Save.
5. Reload the page. Everything — files and windows — is where you left it.

## Good to know

- **Drop files or folders** on a Files window to add them there, or anywhere else to put them on the desktop.
- **Windows** move by their title bar and resize from any edge. Drag one to the top of the screen to
  maximise it, or to the left or right edge to fill that half. Double-click a title bar to maximise.
- **Keys in Files:** arrows move, Enter opens, Backspace goes up, F2 renames, Delete deletes (it asks twice).
- **Your files stay in this browser** — nothing is uploaded. When the page is opened from a file rather
  than a web address, the browser gives it nowhere to keep things, and the desktop says so: it works,
  but forgets when the tab closes.
"""

def emit(name, data):
    rows = [", ".join("0x%02X" % c for c in data[i:i + 32]) for i in range(0, len(data), 32)]
    return "export u8[] %s() {\n  return [\n    %s,\n  ];\n}\n" % (name, ",\n    ".join(rows))

demo = open(os.path.join(root, "samples", "demo.zip"), "rb").read()
out = ["// Generated by tools/seed.py: what a new desktop starts with. Edit tools/seed.py, not this.\n",
       emit("welcomeMd", WELCOME.encode()), emit("demoZip", demo)]
open(os.path.join(root, "src", "desk", "seed.wac"), "w").write("\n".join(out))
print("seed.wac:", len(WELCOME), "bytes of welcome,", len(demo), "bytes of demo.zip")
