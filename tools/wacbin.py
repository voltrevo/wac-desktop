#!/usr/bin/env python3
"""Writes src/desk/wacbin.wac: the `wac` command, as a module, for the desktop's /usr/bin.

Built from the commit wac.lock pins — the same one as everything else here — by the `wac` on PATH, out of the
package cache `wac update` (or tools/use-local-wac.sh) filled. The module is about 3.6 MB; gzipped and in base64 it
is a string of about 1.3 MB, which is how it rides in the page: a page fetches nothing, and a string literal is one
token to the compiler where an array of bytes would be a million.

Generated by `wac task build` and not committed: it is a function of wac.lock, and 1.3 MB of it would be a
new copy in the history every time the pin moves.
"""
import base64, gzip, json, os, re, subprocess, sys, tempfile, urllib.parse

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.normpath(os.path.join(here, ".."))
lock = json.load(open(os.path.join(root, "wac.lock")))
entry = lock["imports"]["wac"]
home = os.environ.get("WAC_HOME") or os.path.join(os.environ["HOME"], ".wac")
src = os.path.join(home, "cache", "git", urllib.parse.quote(entry["git"], safe=""), entry["commit"])
if not os.path.isfile(os.path.join(src, "packages", "wac", "src", "wac.wac")):
    sys.exit("wacbin.py: wac %s is not in the package cache at %s — run `wac update`" % (entry["commit"][:9], src))

with tempfile.TemporaryDirectory() as tmp:
    stem = os.path.join(tmp, "wac")
    done = subprocess.run(["wac", "build", "packages/wac/src/wac.wac", "-o", stem], cwd=src,
                          capture_output=True, text=True)
    if done.returncode != 0:
        sys.exit("wacbin.py: building the wac command failed:\n" + done.stderr + done.stdout)
    module = open(stem + ".wasm", "rb").read()

packed = base64.b64encode(gzip.compress(module, 9, mtime=0)).decode("ascii")
out = os.path.join(root, "src", "desk", "wacbin.wac")
with open(out, "w") as f:
    f.write("// Generated by tools/wacbin.py from wac %s: the `wac` command, gzipped, in base64. Not committed.\n\n"
            "/** The `wac` command's module, %d bytes, gzipped and in base64. */\n"
            "export string wacModuleGz() {\n  return \"%s\";\n}\n" % (entry["commit"][:9], len(module), packed))
print("%s: the wac command, %d bytes, %d gzipped" % (os.path.relpath(out, root), len(module), len(packed) * 3 // 4))
